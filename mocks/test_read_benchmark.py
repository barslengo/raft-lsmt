import os
import json
import time
import subprocess
import unittest
import glob

# Add parent dir to sys.path in case we want to import directly, though we run subprocess
import sys
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from mocks.mock_server import MockDatabaseServer

class TestReadBenchmark(unittest.TestCase):
    def setUp(self):
        # We start three mock servers representing cluster 'A'.
        # Node 1: Leader, listening on 127.0.0.1:18091 (read port: 19091)
        # Node 2: Follower, redirecting to Node 1, listening on 127.0.0.1:18092 (read port: 19092)
        # Node 3: Follower, redirecting to Node 1, listening on 127.0.0.1:18093 (read port: 19093)
        self.servers = [
            MockDatabaseServer("127.0.0.1", 18091, leader_id=1, is_leader=True),
            MockDatabaseServer("127.0.0.1", 18092, leader_id=1, is_leader=False),
            MockDatabaseServer("127.0.0.1", 18093, leader_id=1, is_leader=False),
        ]
        for server in self.servers:
            server.start()

        # Create a mock cluster configuration
        self.config_data = {
            "A": [
                {"id": 1, "host": "127.0.0.1", "raft_port": 17091, "tcp_port": 18091},
                {"id": 2, "host": "127.0.0.1", "raft_port": 17092, "tcp_port": 18092},
                {"id": 3, "host": "127.0.0.1", "raft_port": 17093, "tcp_port": 18093},
            ]
        }
        self.config_file = "test_cluster_conf.json"
        with open(self.config_file, "w") as f:
            json.dump(self.config_data, f)

        # Allow time for mock servers to bind and start listening
        time.sleep(0.5)

    def tearDown(self):
        # Stop servers
        for server in self.servers:
            server.stop()
        
        # Clean up configuration file
        if os.path.exists(self.config_file):
            os.remove(self.config_file)
            
        # Clean up any generated CSVs from the test
        for csv_file in glob.glob("read_throughput_*.csv"):
            try:
                os.remove(csv_file)
            except Exception:
                pass

    def test_benchmark_execution(self):
        # Execute the read_benchmark.py script as a subprocess
        cmd = [
            "python3",
            "read_benchmark.py",
            "--config", self.config_file,
            "--requests", "100",
            "--routing-strategy", "hash",
            "--data-dist", "uniform",
            "--max-key", "1000",
            "--range-size", "5"
        ]
        
        print(f"Running command: {' '.join(cmd)}")
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=15)
        
        # Check that it executed successfully
        print("Subprocess STDOUT:")
        print(result.stdout)
        print("Subprocess STDERR:")
        print(result.stderr)
        
        self.assertEqual(result.returncode, 0, f"Benchmark failed with code {result.returncode}")
        self.assertIn("READ BENCHMARK COMPLETED", result.stdout)
        
        # Verify CSV file creation
        csv_files = glob.glob("read_throughput_*.csv")
        self.assertGreater(len(csv_files), 0, "No CSV file was generated by the benchmark")
        
        # Read the generated CSV and verify the headers and content
        generated_csv = csv_files[0]
        with open(generated_csv, "r") as f:
            lines = f.readlines()
            
        self.assertGreater(len(lines), 0, "Generated CSV is empty")
        header = lines[0].strip()
        
        # Expected header: Timestamp,Total_ACKed_Records,Total_ACKed_Bytes,QPS,MBps,Avg_Latency_ms,P50_Latency_ms,P95_Latency_ms
        expected_header = "Timestamp,Total_ACKed_Records,Total_ACKed_Bytes,QPS,MBps,Avg_Latency_ms,P50_Latency_ms,P95_Latency_ms"
        self.assertEqual(header, expected_header, f"CSV header does not match. Expected '{expected_header}', got '{header}'")
        
        # Check that we have some data rows and they contain numeric values
        if len(lines) > 1:
            data_row = lines[1].strip().split(",")
            self.assertEqual(len(data_row), 8, "Data row must have exactly 8 values")
            # Verify they are convertible to numeric types
            try:
                int(data_row[0])  # Timestamp
                int(data_row[1])  # Total_ACKed_Records
                int(data_row[2])  # Total_ACKed_Bytes
                int(data_row[3])  # QPS
                float(data_row[4])  # MBps
                float(data_row[5])  # Avg_Latency_ms
                float(data_row[6])  # P50_Latency_ms
                float(data_row[7])  # P95_Latency_ms
            except ValueError as e:
                self.fail(f"Failed to parse CSV data values: {e}")

