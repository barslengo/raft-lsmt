# --- GLOBAL METRICS TRACKER ---
metrics_lock = threading.Lock()
total_queries = 0
total_records_read = 0
total_bytes_read = 0
first_request_time = 0.0
last_ack_time = 0.0

MAX_LATENCY_SAMPLES = 10000
latency_samples = [0.0] * MAX_LATENCY_SAMPLES
latency_head = 0
latency_count = 0

def add_latency_sample(latency_ms: float):
    global latency_head, latency_count
    latency_samples[latency_head] = latency_ms
    latency_head = (latency_head + 1) % MAX_LATENCY_SAMPLES
    if latency_count < MAX_LATENCY_SAMPLES:
        latency_count += 1

def calculate_percentile(sorted_samples, percentile):
    count = len(sorted_samples)
    if count == 0:
        return 0.0
    if percentile >= 100.0:
        return float(sorted_samples[-1])
    if percentile <= 0.0:
        return float(sorted_samples[0])
    
    index = (percentile / 100.0) * (count - 1)
    lower = int(index)
    upper = lower + 1
    if upper >= count:
        upper = lower
        
    weight = index - lower
    return (1.0 - weight) * sorted_samples[lower] + weight * sorted_samples[upper]

def get_latency_stats() -> tuple:
    """Returns (avg_latency_ms, p50_latency_ms, p95_latency_ms)"""
    with metrics_lock:
        count = latency_count
        if count == 0:
            return 0.0, 0.0, 0.0
        samples = [latency_samples[i] for i in range(count)]
        
    samples.sort()
    avg_latency = sum(samples) / count
    p50 = calculate_percentile(samples, 50.0)
    p95 = calculate_percentile(samples, 95.0)
    return avg_latency, p50, p95

def update_read_metrics(future, start_time_ms=None):
    """Callback attached to each Future generated by dbclient.read_batch()"""
    global total_queries, total_records_read, total_bytes_read, first_request_time, last_ack_time
    
    current_time_ms = time.time() * 1000
    
    try:
        results = future.result()
        
        # Get the actual network latency calculated inside the client
        latency_ms = results.get("_latency_ms", 0.0)
        
        batch_records = 0
        batch_bytes = 0
        queries_in_batch = 0
        
        for cluster, cluster_results in results.items():
            if cluster == "_latency_ms":
                continue
            for node_dict in cluster_results:
                for _, node_tuple in node_dict.items():
                    _, response_list = node_tuple
                    if response_list:
                        for response in response_list:
                            if response:
                                batch_records += response.get("records_count", 0)
                                batch_bytes += response.get("records_bytes", 0)
                        queries_in_batch = max(queries_in_batch, len(response_list))
        
        with metrics_lock:
            total_queries += queries_in_batch
            total_records_read += batch_records
            total_bytes_read += batch_bytes
            
            if first_request_time == 0.0:
                first_request_time = current_time_ms
            if current_time_ms > last_ack_time:
                last_ack_time = current_time_ms
                
            add_latency_sample(latency_ms)

    except Exception as e:
        import traceback
        print(f"Error in update_read_metrics: {e}", file=sys.stderr)
        traceback.print_exc()

def throughput_reporter(stop_event: threading.Event):
    """
    Background thread that collects metrics and reports throughput/latency.
    - Writes to the CSV file every 1 second.
    - Prints the cumulative counter of completed queries every second.
    """
    seconds_elapsed = 0
    csv_filename = f"read_throughput_{int(time.time())}_{os.getpid()}.csv"
    prev_queries = 0

    with open(csv_filename, "w") as f:
        # Crucial header format compatible with generating dashboards
        f.write("Timestamp,Total_ACKed_Records,Total_ACKed_Bytes,QPS,MBps,Avg_Latency_ms,P50_Latency_ms,P95_Latency_ms\n")

        while not stop_event.wait(1.0):
            seconds_elapsed += 1

            with metrics_lock:
                curr_queries = total_queries
                curr_bytes = total_bytes_read
                curr_records = total_records_read

            avg_l, p50_l, p95_l = get_latency_stats()

            # Write UNIX timestamp and cumulative records, bytes, queries under QPS, and MBs under MBps
            f.write(f"{int(time.time())},{curr_records},{curr_bytes},{curr_queries},{curr_bytes / (1024.0 * 1024.0):.2f},{avg_l:.2f},{p50_l:.2f},{p95_l:.2f}\n")
            f.flush()

            # Every time we add a row, print the counter
            print(f"[{time.strftime('%H:%M:%S')}] Elapsed: {seconds_elapsed}s | Total Queries: {curr_queries:,} | Total Records: {curr_records:,} | Total Bytes: {curr_bytes:,} | Avg Latency: {avg_l:.2f} ms | P50: {p50_l:.2f} ms | P95: {p95_l:.2f} ms")
            sys.stdout.flush()

            prev_queries = curr_queries

        # Write final remaining records if any, or if no data row has been written yet
        with metrics_lock:
            curr_queries = total_queries
            curr_bytes = total_bytes_read
            curr_records = total_records_read

        if curr_queries > prev_queries or seconds_elapsed == 0:
            avg_l, p50_l, p95_l = get_latency_stats()
            f.write(f"{int(time.time())},{curr_records},{curr_bytes},{curr_queries},{curr_bytes / (1024.0 * 1024.0):.2f},{avg_l:.2f},{p50_l:.2f},{p95_l:.2f}\n")
            f.flush()

class ZipfGenerator:
    """Highly optimized Zipfian generator with O(1) time and memory complexity."""
    def __init__(self, n: int, alpha: float = 1.0):
        self.n = max(1, n)
        self.alpha = alpha
        self.is_alpha_one = abs(alpha - 1.0) < 1e-9
        
        if self.is_alpha_one:
            self.c = math.log(self.n)
        else:
            self.c = (self.n ** (1.0 - alpha) - 1.0) / (1.0 - alpha)

    def next(self) -> int:
        u = random.random()
        if self.is_alpha_one:
            val = math.exp(u * self.c)
        else:
            val = (u * self.c * (1.0 - self.alpha) + 1.0) ** (1.0 / (1.0 - self.alpha))
        return min(self.n, max(1, int(val)))

def query_stream(amount: int, data_distribution: str, max_key: int, range_size: int, key_start: int, key_end: int) -> Iterator[QueryRequest]:
    """Generate a stream of QueryRequest objects according to the specified distribution."""
    print(f"Initializing {amount} queries stream (Data Dist: {data_distribution}, Max Key: {max_key}, Key Range: [{key_start}, {key_end}], Range Size: {range_size})...")
    
    max_ts = (2**64) - 1
    range_width = key_end - key_start + 1

    if data_distribution == 'sequential':
        for i in range(amount):
            start_id = key_start + (i * range_size) % range_width
            yield QueryRequest(min_id=start_id, min_ts=0, max_id=start_id + range_size - 1, max_ts=max_ts)
            
    elif data_distribution == 'uniform':
        for _ in range(amount):
            start_id = random.randint(key_start, key_end)
            yield QueryRequest(min_id=start_id, min_ts=0, max_id=start_id + range_size - 1, max_ts=max_ts)
            
    elif data_distribution == 'zipfian':
        zipf = ZipfGenerator(range_width)
        for _ in range(amount):
            start_id = key_start + zipf.next() - 1
            yield QueryRequest(min_id=start_id, min_ts=0, max_id=start_id + range_size - 1, max_ts=max_ts)
    else:
        raise ValueError(f"Unknown distribution: {data_distribution}")

def bench(dbclient: DbClient, data_dist: str, requests: int, max_key: int, range_size: int, batch_size: int, key_start: int, key_end: int):
    """
    Query benchmark loop with batching. Uses the client's internal ThreadPoolExecutor.
    """
    futures = []
    max_pending_futures = 512  # Backpressure to avoid saturating RAM
    
    stop_event = threading.Event()
    reporter_thread = threading.Thread(target=throughput_reporter, args=(stop_event,), daemon=True)
    reporter_thread.start()

    stream = query_stream(requests, data_dist, max_key, range_size, key_start, key_end)
    total_processed = 0
    batch_buffer = []
    
    for query in stream:
        batch_buffer.append(query)
        total_processed += 1

        if total_processed % 100_000 == 0:
            timestamp = time.strftime('%H:%M:%S')
            print(f"[{timestamp}] ⏳ Progress: {total_processed:,} queries generated...")

        if len(batch_buffer) >= batch_size:
            # Send batch request to client. dbclient.read_batch() returns a Future.
            start_time = time.time() * 1000
            f = dbclient.read_batch(batch_buffer, skip_records=True)
            # Register callback to count results
            f.add_done_callback(lambda fut, st=start_time: update_read_metrics(fut, st))
            futures.append(f)
            batch_buffer = []
            
            # Apply Backpressure
            if len(futures) > max_pending_futures:
                done, not_done = wait(futures, return_when=FIRST_COMPLETED)
                futures = list(not_done)
                
    # Send any remaining queries
    if batch_buffer:
        start_time = time.time() * 1000
        f = dbclient.read_batch(batch_buffer, skip_records=True)
        f.add_done_callback(lambda fut, st=start_time: update_read_metrics(fut, st))
        futures.append(f)
    
    print("All queries generated. Waiting for remaining queries to finish...")
    
    # Wait for the remaining futures
    if len(futures) > 0:
        wait(futures)

    stop_event.set()
    reporter_thread.join()

    global total_queries, total_records_read, total_bytes_read, first_request_time, last_ack_time

    total_time_sec = (last_ack_time - first_request_time) / 1000.0

    print("\n" + "="*50)
    print("🏁 READ BENCHMARK COMPLETED")
    print("="*50)
    if total_time_sec > 0:
        print(f"Total time elapsed:  {total_time_sec:.2f} s")
        print(f"Total Queries:       {total_queries:,}")
        print(f"Total Records read:  {total_records_read:,}")
        print(f"Overall QPS:         {total_queries / total_time_sec:,.2f} qps")
        print(f"Overall Bandwidth:   {total_bytes_read / 1024 / 1024 / total_time_sec:.2f} MB/s")
        
        avg_l, p50_l, p95_l = get_latency_stats()
        print(f"Avg Latency:         {avg_l:.2f} ms")
        print(f"P50 Latency:         {p50_l:.2f} ms")
        print(f"P95 Latency:         {p95_l:.2f} ms")
    else:
        print("No metrics recorded or time was too short.")

    dbclient.disconnect()

def main():
    parser = argparse.ArgumentParser(description="Raft DB READ benchmark")
    parser.add_argument("--config", required=True, help="Path to cluster_conf.json")
    parser.add_argument("--requests", type=int, default=1000000, help="Number of read queries to execute")
    parser.add_argument("--routing-strategy", 
                        choices=["hash", "round-robin", "leader"], 
                        default="hash", 
                        help="Routing strategy to use")
    parser.add_argument("--data-dist", 
                        choices=["sequential", "uniform", "zipfian"], 
                        default="uniform", 
                        help="Query key distribution strategy")
    parser.add_argument("--max-key", type=int, default=5000000, help="The maximum key ID existing in the database")
    parser.add_argument("--range-size", type=int, default=10, help="How many keys to fetch per query (Range Size)")
    parser.add_argument("--thread-pool-size", type=int, default=16, help="Thread pool size for concurrent I/O requests")
    parser.add_argument("--batch-size", type=int, default=32, help="Number of query requests to batch together")
    
    parser.add_argument("--key-start", type=int, default=1, help="Start of the key range (inclusive)")
    parser.add_argument("--key-end", type=int, default=None, help="End of the key range (inclusive)")
    
    args = parser.parse_args()

    if args.key_end is None:
        args.key_end = args.max_key

    with open(args.config, 'r') as f:
        config_data = json.load(f)
    
    clusters = {}
    for cluster_name, nodes_data in config_data.items():
        clusters[cluster_name] = [
            Node(cluster_name=cluster_name, id=n['id'], host=n['host'], port=n['tcp_port'])
            for n in nodes_data
        ]
    
    strategy_map = {
        "hash": HashRoutingStrategy(),
        "round-robin": RoundRobinRoutingStrategy(),
        "leader": LeaderRoutingStrategy()
    }
    strategy = strategy_map[args.routing_strategy]
    router = Router(strategy)
    router.update_topology(clusters)
    
    client_config = DbClientConfig(
        thread_pool_size=args.thread_pool_size,
        batch_size=4096,
        write_timeout=5.0,
        read_timeout=15.0,
    )

    db_client = DbClient(client_config, router)
    db_client.connect(clusters)
    
    print(f"Connected to {sum(len(nodes) for nodes in clusters.values())} nodes across {len(clusters)} clusters")
    print(f"Routing strategy: {args.routing_strategy}")
    print(f"Batch size: {args.batch_size}")
    
    try:
        bench(db_client, args.data_dist, args.requests, args.max_key, args.range_size, args.batch_size, args.key_start, args.key_end)
    except Exception as e:
        print(f"Error: {e}")
        db_client.disconnect()
        sys.exit(1)

if __name__ == "__main__":
    main()
