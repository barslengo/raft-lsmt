# --- GLOBAL METRICS TRACKER ---
metrics_lock = threading.Lock()
total_queries = 0
total_records_read = 0
total_bytes_read = 0
first_request_time = 0.0
last_ack_time = 0.0
successful_requests = []
CURRENT_PID = os.getpid()

def calculate_percentile(sorted_samples, percentile):
    count = len(sorted_samples)
    if count == 0:
        return 0.0
    if percentile >= 100.0:
        return float(sorted_samples[-1])
    if percentile <= 0.0:
        return float(sorted_samples[0])
    
    index = (percentile / 100.0) * (count - 1)
    lower = int(index)
    upper = lower + 1
    if upper >= count:
        upper = lower
        
    weight = index - lower
    return (1.0 - weight) * sorted_samples[lower] + weight * sorted_samples[upper]

def update_read_metrics(future, start_time_ms=None, num_queries=None):
    """Callback attached to each Future generated by dbclient.read_batch()"""
    global total_queries, total_records_read, total_bytes_read, first_request_time, last_ack_time
    try:
        results = future.result()
        req_metrics = results.get("_request_metrics", [])
        
        queries_in_batch = num_queries if num_queries is not None else 0
        
        with metrics_lock:
            total_queries += queries_in_batch
            for metrics in req_metrics:
                unique_query_id = CURRENT_PID * 100000000 + metrics.query_id
                unique_request_id = CURRENT_PID * 100000000 + metrics.req_id
                unique_metrics = replace(metrics, query_id=unique_query_id, req_id=unique_request_id)
                
                successful_requests.append(unique_metrics)
                total_records_read += metrics.record_count
                total_bytes_read += metrics.records_bytes
                
                if first_request_time == 0.0 or metrics.send_time_ms < first_request_time:
                    first_request_time = metrics.send_time_ms
                if metrics.recv_time_ms > last_ack_time:
                    last_ack_time = metrics.recv_time_ms
    except Exception as e:
        import traceback
        print(f"Error in update_read_metrics: {e}", file=sys.stderr)
        traceback.print_exc()

def throughput_reporter(stop_event: threading.Event):
    """
    Background thread that reports throughput status to the console.
    Does NOT calculate heavy latency statistics or write to CSV to avoid overhead.
    """
    seconds_elapsed = 0
    while not stop_event.wait(5.0):
        seconds_elapsed += 1
        with metrics_lock:
            curr_queries = total_queries
            curr_bytes = total_bytes_read
            curr_records = total_records_read
        print(f"[{time.strftime('%H:%M:%S')}] Elapsed: {seconds_elapsed}s | Total Queries: {curr_queries:,} | Total Records: {curr_records:,} | Total Bytes: {curr_bytes:,}")
